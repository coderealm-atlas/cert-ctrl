import { describe, expect, it } from 'vitest';
import { installHandler } from './install.js';

describe('installer hostname migration', () => {
  it.each(['install.sh', 'install-macos.sh', 'install.ps1'])(
    'serves %s on the legacy host with canonical update URLs',
    async (path) => {
      const response = await installHandler(
        new Request(`https://install.lets-script.com/${path}`),
        { CURRENT_HOST: 'install.never-lost.app' }
      );
      expect(response.status).toBe(200);
      const script = await response.text();
      expect(script).toContain('https://install.never-lost.app');
      expect(script).not.toContain('install.lets-script.com');
      expect(script).toContain('https://install.never-lost.app/releases/proxy');
    }
  );

  it('honors the configured installer host for staging', async () => {
    const response = await installHandler(
      new Request('https://install-staging.cjj365.cc/install.sh'),
      { CURRENT_HOST: 'install-staging.cjj365.cc' }
    );
    const script = await response.text();
    expect(script).toContain('https://install-staging.cjj365.cc/releases/proxy');
    expect(script).toContain('Generated by: https://install-staging.cjj365.cc');
  });
});
